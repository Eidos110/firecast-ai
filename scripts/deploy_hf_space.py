#!/usr/bin/env python3
"""Deploy FireCast to HuggingFace Space (build-only, allowlist staging).

Target: ``Kaido1/firecast-private`` (public Docker Space, cpu-basic).

Why build-only?
    The React SPA is compiled locally (``npm run build``) and only the
    ``frontend_react/build/`` output is shipped — React sources, tests,
    notebooks, docs and the legacy Streamlit tree never reach the Space.
    Python runtime (``src/``) must ship as-is (interpreted language).

Why allowlist staging?
    A prior deploy leaked a GEE service-account key because
    ``upload_folder`` does NOT respect ``.gitignore``. This script copies an
    explicit allowlist into a temp staging dir, so nothing outside the list
    can ever be uploaded.

Usage:
    $env:HF_TOKEN = "<hf_...>"          # write-access token
    python scripts/deploy_hf_space.py   # build + stage + upload + verify

The Space secret ``API_SECRET_KEY`` is managed in the HF UI/API (encrypted),
never in this repo.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPO_ID = "Kaido1/firecast-private"
SPACE_URL = f"https://{REPO_ID.replace('/', '-').lower()}.hf.space"

# ---------------------------------------------------------------------------
# Allowlist: exactly what the runtime needs, nothing else.
# ---------------------------------------------------------------------------
ALLOW_DIRS = {
    "src": None,  # whole dir
    "models": None,  # whole dir (legacy CNN+LGBM bundle)
}
ALLOW_FILES_ROOT = ["requirements.txt", "start_api.py"]
# add_new_model: everything except notebooks (training artefacts)
ADD_NEW_MODEL_EXCLUDE_SUFFIX = {".ipynb"}
# data: parquet twins + locations only (loader prefers parquet; ~64 MB saved)
DATA_ALLOW = ["locations.json"]
DATA_ALLOW_SUFFIX = [".parquet"]


DOCKERFILE = """\
# =====================================================================
# FireCast — Single-stage Dockerfile (HF Spaces build-only deploy)
# =====================================================================
# The React SPA is pre-built locally (`npm run build`) and shipped as
# `frontend_react/build/` — no Node stage, no React sources on the Space.
# Generated by scripts/deploy_hf_space.py — do not edit the staged copy.
# =====================================================================

FROM python:3.12-slim AS base

WORKDIR /app

RUN apt-get update && apt-get install -y --no-install-recommends \\
        gcc \\
        g++ \\
        libgomp1 \\
        libglib2.0-0 \\
        libsm6 \\
        libxext6 \\
        libxrender-dev \\
        curl \\
    && rm -rf /var/lib/apt/lists/*

COPY requirements.txt ./

# CPU-only PyTorch wheels; nvidia-nccl-cu12 is a hard metadata dep of
# xgboost>=3.0 on Linux but never imported on the CPU path — uninstall it
# so the ~340 MB CUDA lib does not bloat this image.
RUN pip install --no-cache-dir \\
        --extra-index-url https://download.pytorch.org/whl/cpu \\
        -r requirements.txt \\
    && (pip uninstall -y nvidia-nccl-cu12 || echo "nvidia-nccl-cu12 not present")

COPY . .

RUN mkdir -p /app/models /app/data

ENV PYTHONPATH=/app \\
    PORT=7860 \\
    HOST=0.0.0.0 \\
    ML_DEVICE=cpu

EXPOSE 7860

HEALTHCHECK --interval=30s --timeout=10s --start-period=60s --retries=3 \\
    CMD curl -f http://localhost:7860/health || exit 1

CMD ["python", "start_api.py"]
"""

README = """\
---
title: Firecast Fire Risk Predictor
emoji: 🔥
colorFrom: red
colorTo: yellow
sdk: docker
pinned: false
---

# 🔥 FireCast

**Fire Risk Prediction System using Ensemble Machine Learning**

Interactive map-based fire risk prediction for Indonesia. V4.2 two-leg stack
(LightGBM + XGBoost + LogisticRegressionCV meta, isotonic calibration) with
SHAP explainability, served as a single FastAPI + React SPA service.

## Runtime

- **Backend**: FastAPI (`src/`) — `/predict`, `/predict/aoi`,
  `/geo/*`, `/analytics/*`, `/api/models/*`, `/health`
- **Frontend**: pre-built React SPA (`frontend_react/build/`) — source is not
  shipped with this Space
- **Models**: `add_new_model/` (V4.2 stack + calibrator) and `models/`
  (legacy CNN + LightGBM bundle for `model_type="legacy"`)
- **Data**: Parquet feature datasets (`data/*.parquet`) + `locations.json`

## Notes

- CPU-only inference (PyTorch CPU wheels, `ML_DEVICE=cpu`).
- Rate limits: 30 req/min per IP on `/predict`; 10/min on `/predict/aoi`.
- `/predict` requires the `X-API-Key` header (Space secret `API_SECRET_KEY`).
"""


def build_spa() -> None:
    print("[1/5] building React SPA (npm run build)...")
    spa = REPO_ROOT / "frontend_react"
    subprocess.run("npm run build", cwd=spa, shell=True, check=True)
    if not (spa / "build" / "index.html").exists():
        sys.exit("SPA build produced no build/index.html")


def stage(staging: Path) -> int:
    print(f"[2/5] staging allowlist -> {staging}")
    for name in ALLOW_DIRS:
        shutil.copytree(REPO_ROOT / name, staging / name)
    for name in ALLOW_FILES_ROOT:
        shutil.copy2(REPO_ROOT / name, staging / name)

    (staging / "add_new_model").mkdir()
    for f in (REPO_ROOT / "add_new_model").iterdir():
        if f.is_file() and f.suffix not in ADD_NEW_MODEL_EXCLUDE_SUFFIX:
            shutil.copy2(f, staging / "add_new_model" / f.name)

    (staging / "data").mkdir()
    for f in (REPO_ROOT / "data").iterdir():
        if f.is_file() and (f.name in DATA_ALLOW or f.suffix in DATA_ALLOW_SUFFIX):
            shutil.copy2(f, staging / "data" / f.name)

    (staging / "frontend_react" / "build").mkdir(parents=True)
    shutil.copytree(
        REPO_ROOT / "frontend_react" / "build",
        staging / "frontend_react" / "build",
        dirs_exist_ok=True,
    )

    (staging / "Dockerfile").write_text(DOCKERFILE, encoding="utf-8")
    (staging / "README.md").write_text(README, encoding="utf-8")

    files = [p for p in staging.rglob("*") if p.is_file()]
    total_mb = sum(p.stat().st_size for p in files) / 1e6
    print(f"      {len(files)} files, {total_mb:.1f} MB")

    # Hard leak guards — fail loudly if the allowlist ever drifts.
    forbidden = [
        p
        for p in files
        if p.suffix in {".tsx", ".ts", ".ipynb"}
        or p.name.startswith(".env")
        or "firecast-001" in p.name
        or "secrets" in p.parts
    ]
    if forbidden:
        sys.exit(f"REFUSING upload — forbidden files staged: {forbidden[:5]}")
    return len(files)


def upload(staging: Path) -> str:
    print("[3/5] uploading to Space (delete_patterns=['*'] clears stale files)...")
    from huggingface_hub import HfApi

    token = os.environ.get("HF_TOKEN")
    if not token:
        sys.exit("HF_TOKEN not set")
    api = HfApi(token=token)
    print(f"      identity: {api.whoami()['name']}")
    commit = api.upload_folder(
        folder_path=str(staging),
        repo_id=REPO_ID,
        repo_type="space",
        commit_message="Deploy FireCast SPA (build-only, allowlist staging)",
        delete_patterns=["*"],
    )
    oid = getattr(commit, "oid", "n/a")
    print(f"      commit oid: {oid}")
    return oid


def wait_running(timeout_s: int = 900) -> None:
    print("[4/5] waiting for Space to reach RUNNING...")
    from huggingface_hub import HfApi

    api = HfApi(token=os.environ["HF_TOKEN"])
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        info = api.repo_info(REPO_ID, repo_type="space")
        stage_name = info.runtime.stage if info.runtime else "n/a"
        print(f"      stage={stage_name}")
        if stage_name == "RUNNING":
            return
        if stage_name in ("BUILD_ERROR", "APP_START_FAILED", "CONFIG_ERROR"):
            sys.exit(f"Space failed: {stage_name} — check build logs in the HF UI")
        time.sleep(20)
    sys.exit("timeout waiting for RUNNING")


def verify() -> None:
    print("[5/5] verifying live endpoints...")
    for path in ("/health", "/"):
        with urllib.request.urlopen(f"{SPACE_URL}{path}", timeout=30) as r:
            assert r.status == 200, f"{path} -> {r.status}"
            print(f"      GET {path} -> {r.status}")
    print(f"\nDEPLOY OK — {SPACE_URL}")
    print("Note: /predict needs the X-API-Key header (Space secret API_SECRET_KEY).")


def main() -> None:
    build_spa()
    staging = Path(tempfile.mkdtemp(prefix="firecast_hf_stage_"))
    try:
        stage(staging)
        upload(staging)
        wait_running()
        verify()
    finally:
        shutil.rmtree(staging, ignore_errors=True)


if __name__ == "__main__":
    main()
